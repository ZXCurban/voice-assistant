def main() -> None:
    import sys

    assert len(E) == 200, f"expected 200 new entries, got {len(E)}"
    root = Path(__file__).resolve().parents[1]
    data = root / "backend" / "tests" / "eval" / "data"
    v1 = [
        json.loads(line)
        for line in (data / "clinic_intents_v1.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    existing_texts = {r["text"].strip() for r in v1}
    rows = []
    for i, (text, intent, nh, nc, wf, tool, cat, notes, ctx) in enumerate(E, start=401):
        assert text.strip() not in existing_texts, f"dup text: {text}"
        existing_texts.add(text.strip())
        row = {
            "id": f"clinic_{i:04d}",
            "text": text,
            "expected_intent": intent,
            "expected_needs_human": nh,
            "expected_needs_clarification": nc,
            "expected_workflow": wf,
            "expected_tool": tool,
            "category": cat,
            "notes": notes,
        }
        if ctx:
            row["context"] = ctx
        rows.append(row)
    full = v1 + rows
    with open(data / "clinic_intents_v2.jsonl", "w", encoding="utf-8") as f:
        for r in full:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    # v2 splits: frozen v1 test core (80) + new items (seed 43): 120 calib / 40 valid / 40 test
    rng = random.Random(43)
    idx = list(range(len(rows)))
    rng.shuffle(idx)
    new_cal = [rows[i] for i in idx[:120]]
    new_val = [rows[i] for i in idx[120:160]]
    new_test = [rows[i] for i in idx[160:]]

    def load(name: str) -> list:
        return [
            json.loads(line)
            for line in (data / name).read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]

    splits = {
        "calibration": load("split_calibration.jsonl") + new_cal,
        "validation": load("split_validation.jsonl") + new_val,
        "test": load("split_test.jsonl") + new_test,
    }
    assert (
        len(splits["calibration"]) == 360
        and len(splits["validation"]) == 120
        and len(splits["test"]) == 120
    )
    for name, part in splits.items():
        with open(data / f"split_{name}_v2.jsonl", "w", encoding="utf-8") as f:
            for r in part:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("v2 total:", len(full), {k: len(v) for k, v in splits.items()})


if __name__ == "__main__":
    main()
