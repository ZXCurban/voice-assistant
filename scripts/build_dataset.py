def main() -> None:
    assert len(E) == 400, f"expected 400 entries, got {len(E)}"
    out_dir = Path("backend/tests/eval/data")
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for i, (text, intent, nh, nc, wf, tool, cat, notes) in enumerate(E, start=1):
        rows.append(
            {
                "id": f"clinic_{i:04d}",
                "text": text,
                "expected_intent": intent,
                "expected_needs_human": nh,
                "expected_needs_clarification": nc,
                "expected_workflow": wf,
                "expected_tool": tool,
                "category": cat,
                "notes": notes,
            }
        )
    with open(out_dir / "clinic_intents_v1.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    # deterministic split 240/80/80, seed 42
    rng = random.Random(42)
    idx = list(range(400))
    rng.shuffle(idx)
    splits = {
        "calibration": [rows[i] for i in idx[:240]],
        "validation": [rows[i] for i in idx[240:320]],
        "test": [rows[i] for i in idx[320:]],
    }
    for name, part in splits.items():
        with open(out_dir / f"split_{name}.jsonl", "w", encoding="utf-8") as f:
            for r in part:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"wrote {len(rows)} rows + splits")


if __name__ == "__main__":
    main()
